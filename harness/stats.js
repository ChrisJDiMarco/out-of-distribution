#!/usr/bin/env node
// Builds site/data.js from every match record plus the bot calibration.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { createGame } from '../engine/afterlight-engine.js';
import { buildPrompt, SYSTEM_PROMPT, RULES } from './prompt.js';
import { ENGINE_SHA, RULES_SHA } from './match.js';
import { PLAYERS, makePlayer } from './players.js';
import { ROUNDS } from './schedule.js';

const ROOT = new URL('..', import.meta.url).pathname;
const MATCH_DIR = join(ROOT, 'data', 'matches');
const readJson = file => JSON.parse(readFileSync(file, 'utf8'));

// Pending entrants are shown on the page but have not played yet.
const PENDING = {
  'gpt-6-astra': 'Scheduled. Its games post here as soon as they are played.',
};
// Every scheduled league round counts; 'dev' games only appear in local previews.
const INCLUDE_ROUNDS = new Set([...Object.keys(ROUNDS), ...(process.env.OOD_DEV ? ['dev'] : [])]);

const matches = readdirSync(MATCH_DIR)
  .filter(name => name.endsWith('.json'))
  .map(name => readJson(join(MATCH_DIR, name)))
  .filter(m => m.status === 'finished' && INCLUDE_ROUNDS.has(m.round) && m.engine === ENGINE_SHA && m.rules === RULES_SHA)
  .sort((a, b) => a.createdAt.localeCompare(b.createdAt));

const compactMatch = m => ({
  id: m.id,
  round: m.round,
  createdAt: m.createdAt,
  players: { amber: m.players.amber, blue: m.players.blue },
  result: m.result,
  plies: m.plies.map(p => ({
    s: p.side === 'amber' ? 0 : 1,
    m: p.move,
    c: p.commentary || null,
    t: p.latencyMs || 0,
    f: p.fumble ? 1 : 0,
    a: p.attempts || 1,
    o: (p.calls || []).reduce((sum, c) => sum + (c.usage?.output || 0), 0) || null,
    usd: (p.calls || []).reduce((sum, c) => sum + (c.costUsd || 0), 0) || null,
  })),
});

const ids = new Set(matches.flatMap(m => [m.players.amber.id, m.players.blue.id]));
for (const id of Object.keys(PENDING)) ids.add(id);
const players = [...ids].map(id => {
  const p = PLAYERS[id] ? makePlayer(id) : { id, label: id, kind: 'unknown' };
  return { id, label: p.label, kind: p.kind, vendor: p.vendor ?? null, model: p.model ?? null, effort: p.effort ?? null, pending: PENDING[id] && !matches.some(m => [m.players.amber.id, m.players.blue.id].includes(id)) ? PENDING[id] : null };
});

const calibrationFile = join(ROOT, 'data', 'calibration', 'ladder.json');
const calibration = existsSync(calibrationFile) ? readJson(calibrationFile) : null;
const cleanroomFile = join(ROOT, 'data', 'cleanroom.json');
const cleanroom = existsSync(cleanroomFile) ? readJson(cleanroomFile) : null;

const data = {
  meta: {
    generatedAt: new Date().toISOString(),
    engineSha: ENGINE_SHA,
    rulesSha: RULES_SHA,
    game: { name: 'Afterlight', invented: '2026-09-05', inventedBy: 'GPT-6 Astra' },
    systemPrompt: SYSTEM_PROMPT,
    rules: RULES,
    examplePrompt: buildPrompt({ state: createGame(), lastPly: null }),
    cleanroom,
  },
  players,
  matches: matches.map(compactMatch),
  calibration: calibration && { gamesPerOrder: calibration.gamesPerOrder, openingRandomTurns: calibration.openingRandomTurns, pairs: calibration.pairs.map(({ plies, ...rest }) => ({ ...rest, avgTurns: +(plies.reduce((s, x) => s + x, 0) / plies.length).toFixed(1) })), mirrors: calibration.mirrors },
};

writeFileSync(join(ROOT, 'site', 'data.js'), `// Generated by harness/stats.js. Do not edit by hand.\nexport default ${JSON.stringify(data)};\n`);
console.log(`site/data.js: ${matches.length} finished match(es), ${players.length} player(s)`);
